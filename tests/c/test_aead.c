/* test_aead.c — L0/L1 for the AES-256-GCM adapter (B-23 / F4).
 *
 * Two independent vector sources, deliberately kept separate:
 *
 * 1. test_cavp_*(): official NIST CAVP vectors from gcmEncryptExtIV256.rsp
 *    (AES-256, IVlen=96, Taglen=128), transcribed from
 *    quiche/quic/core/crypto/aes_256_gcm_encrypter_test.cc. Transcription
 *    confirmed by tools/verify_cavp.py, which re-derives every vector with
 *    Python `cryptography` (a separate implementation) byte-for-byte.
 *    Covers: empty PT, AAD-only, 128-bit PT, 408-bit PT with 160-bit AAD
 *    (multi-block, partial final block), 104-bit PT.
 *
 * 2. test_vector_*(): cross-implementation agreement against vectors
 *    generated by Python `cryptography` at authoring time. These are NOT
 *    CAVP vectors; they exist to catch regressions in the our-own
 *    key/nonce patterns used elsewhere in the codebase.
 */
#include "unity.h"

#include <stdio.h>
#include <string.h>

#include "qc_aead.h"

static void fill_key_nonce(uint8_t key[32], uint8_t nonce[12]) {
    for (int i = 0; i < 32; i++) {
        key[i] = (uint8_t)i;
    }
    for (int i = 0; i < 12; i++) {
        nonce[i] = (uint8_t)(0xA0 + i);
    }
}

static void expect_hex_n(const char *label, const uint8_t *got, size_t n,
                         const char *want_hex) {
    char buf[257];
    static const char hd[] = "0123456789abcdef";
    /* Unity rejects zero-length compares; empty ciphertext is a real case
     * (CAVP empty-PT vectors), so assert the expected shape instead. */
    if (n == 0) {
        TEST_ASSERT_EQUAL_STRING_MESSAGE("", want_hex, label);
        return;
    }
    for (size_t i = 0; i < n; i++) {
        buf[2 * i] = hd[(got[i] >> 4) & 0xF];
        buf[2 * i + 1] = hd[got[i] & 0xF];
    }
    buf[2 * n] = '\0';
    TEST_ASSERT_EQUAL_STRING_MESSAGE(want_hex, buf, label);
}

/* Decode lowercase hex into out; caller guarantees out is large enough.
 * TEST only — never on secret data. */
static size_t hex_decode(const char *hex, uint8_t *out, size_t out_cap) {
    size_t n = strlen(hex) / 2;
    TEST_ASSERT_TRUE_MESSAGE(n <= out_cap, "hex longer than buffer");
    for (size_t i = 0; i < n; i++) {
        unsigned v;
        TEST_ASSERT_EQUAL_INT_MESSAGE(1, sscanf(hex + 2 * i, "%2x", &v),
                                      "bad hex");
        out[i] = (uint8_t)v;
    }
    return n;
}

/* One CAVP vector: encrypt must reproduce the NIST CT and tag; decrypt
 * of the NIST CT with the NIST tag must recover the PT. Both directions
 * use the published constants — never our own output as the oracle. */
static void run_cavp(const char *label,
                     const char *key_hex, const char *iv_hex,
                     const char *pt_hex, const char *aad_hex,
                     const char *ct_hex, const char *tag_hex) {
    uint8_t key[32], iv[12];
    uint8_t pt[64], aad[32], ct[64], tag[16], back[64];
    uint8_t nist_ct[64], nist_tag[16];
    size_t pt_len, aad_len, nist_ct_len;
    int rc;

    hex_decode(key_hex, key, sizeof(key));
    hex_decode(iv_hex, iv, sizeof(iv));
    pt_len = hex_decode(pt_hex, pt, sizeof(pt));
    aad_len = hex_decode(aad_hex, aad, sizeof(aad));
    nist_ct_len = hex_decode(ct_hex, nist_ct, sizeof(nist_ct));
    hex_decode(tag_hex, nist_tag, sizeof(nist_tag));
    TEST_ASSERT_EQUAL_UINT_MESSAGE(pt_len, nist_ct_len, label);

    rc = qc_aead_encrypt(key, sizeof(key), iv, sizeof(iv),
                         aad_len ? aad : NULL, aad_len,
                         pt_len ? pt : NULL, pt_len, ct, tag);
    TEST_ASSERT_EQUAL_INT_MESSAGE(QC_AEAD_OK, rc, label);
    expect_hex_n(label, ct, pt_len, ct_hex);
    expect_hex_n(label, tag, sizeof(tag), tag_hex);

    rc = qc_aead_decrypt(key, sizeof(key), iv, sizeof(iv),
                         aad_len ? aad : NULL, aad_len,
                         pt_len ? nist_ct : NULL, nist_ct_len,
                         nist_tag, back);
    TEST_ASSERT_EQUAL_INT_MESSAGE(QC_AEAD_OK, rc, label);
    if (pt_len > 0) {
        TEST_ASSERT_EQUAL_UINT8_ARRAY_MESSAGE(pt, back, pt_len, label);
    }

    /* Flip one AAD bit: must fail auth, and must not release plaintext. */
    if (aad_len > 0) {
        uint8_t bad_aad[32];
        memcpy(bad_aad, aad, aad_len);
        bad_aad[0] ^= 0x01;
        memset(back, 0x5A, sizeof(back));
        rc = qc_aead_decrypt(key, sizeof(key), iv, sizeof(iv),
                             bad_aad, aad_len, ct, pt_len, tag, back);
        TEST_ASSERT_EQUAL_INT_MESSAGE(QC_AEAD_AUTH_FAIL, rc, label);
        for (size_t i = 0; i < pt_len; i++) {
            TEST_ASSERT_EQUAL_UINT8_MESSAGE(0, back[i], label);
        }
    }
}

