static void test_vector_empty(void) {
    uint8_t key[32], nonce[12], ct[1], tag[16], pt[1];
    int rc;

    fill_key_nonce(key, nonce);
    rc = qc_aead_encrypt(key, 32, nonce, 12, NULL, 0, NULL, 0, ct, tag);
    TEST_ASSERT_EQUAL_INT_MESSAGE(QC_AEAD_OK, rc, "enc rc");
    expect_hex_n("empty tag", tag, 16,
                 "5c699625af4b93a0f8220a2a6119c5d0");
    rc = qc_aead_decrypt(key, 32, nonce, 12, NULL, 0, NULL, 0, tag, pt);
    TEST_ASSERT_EQUAL_INT_MESSAGE(QC_AEAD_OK, rc, "dec rc");
}

static void test_vector_msg16(void) {
    uint8_t key[32], nonce[12], pt[16], ct[16], tag[16], back[16];
    static const char *aad = "header-data";
    int rc;

    fill_key_nonce(key, nonce);
    for (int i = 0; i < 16; i++) {
        pt[i] = (uint8_t)i;
    }
    rc = qc_aead_encrypt(key, 32, nonce, 12, (const uint8_t *)aad, 11,
                         pt, sizeof(pt), ct, tag);
    TEST_ASSERT_EQUAL_INT_MESSAGE(QC_AEAD_OK, rc, "enc rc");
    expect_hex_n("msg16 ct", ct, 16, "e6197e2e41ce04b86a6c8dd80b77ced1");
    expect_hex_n("msg16 tag", tag, 16, "16a76f62bad871863594584211677607");
    rc = qc_aead_decrypt(key, 32, nonce, 12, (const uint8_t *)aad, 11,
                         ct, sizeof(ct), tag, back);
    TEST_ASSERT_EQUAL_INT_MESSAGE(QC_AEAD_OK, rc, "dec rc");
    TEST_ASSERT_EQUAL_UINT8_ARRAY_MESSAGE(pt, back, 16, "roundtrip");
}

