void tearDown(void) {}

int main(void) {
    UNITY_BEGIN();
    /* Official NIST CAVP vectors (primary correctness evidence). */
    RUN_TEST(test_cavp_empty);
    RUN_TEST(test_cavp_aad_only);
    RUN_TEST(test_cavp_pt128);
    RUN_TEST(test_cavp_multiblock);
    RUN_TEST(test_cavp_partial_block);
    /* Cross-implementation agreement (regression guard). */
    RUN_TEST(test_vector_empty);
    RUN_TEST(test_vector_msg16);
    RUN_TEST(test_vector_msg64);
    /* Misuse taxonomy. */
    RUN_TEST(test_null_guards_encrypt);
    RUN_TEST(test_null_guards_decrypt);
    RUN_TEST(test_misuse_taxonomy);
    return UNITY_END();
}
