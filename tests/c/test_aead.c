/* Every input-validation branch in qc_aead.c gets at least one test.
 * check_common: NULL key, NULL nonce, short key, short nonce — on both
 * paths. Per-call guards: NULL pt/ct/tag/aad with nonzero length —
 * on both paths. */
static void test_null_guards_encrypt(void) {
    uint8_t key[32], nonce[12], pt[16], ct[16], tag[16];
    int rc;

    fill_key_nonce(key, nonce);
    memset(pt, 0x33, sizeof(pt));
    rc = qc_aead_encrypt(key, 32, nonce, 12, NULL, 0, pt, sizeof(pt),
                         ct, tag);
    TEST_ASSERT_EQUAL_INT(QC_AEAD_OK, rc);

    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_KEY,
                          qc_aead_encrypt(NULL, 32, nonce, 12, NULL, 0,
                                          pt, sizeof(pt), ct, tag));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_LENGTH,
                          qc_aead_encrypt(key, 32, NULL, 12, NULL, 0,
                                          pt, sizeof(pt), ct, tag));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_KEY,
                          qc_aead_encrypt(key, 16, nonce, 12, NULL, 0,
                                          pt, sizeof(pt), ct, tag));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_LENGTH,
                          qc_aead_encrypt(key, 32, nonce, 11, NULL, 0,
                                          pt, sizeof(pt), ct, tag));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_LENGTH,
                          qc_aead_encrypt(key, 32, nonce, 12, NULL, 0,
                                          NULL, sizeof(pt), ct, tag));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_LENGTH,
                          qc_aead_encrypt(key, 32, nonce, 12, NULL, 0,
                                          pt, sizeof(pt), NULL, tag));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_LENGTH,
                          qc_aead_encrypt(key, 32, nonce, 12, NULL, 0,
                                          pt, sizeof(pt), ct, NULL));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_LENGTH,
                          qc_aead_encrypt(key, 32, nonce, 12, NULL, 1,
                                          pt, sizeof(pt), ct, tag));
}

static void test_null_guards_decrypt(void) {
    uint8_t key[32], nonce[12], pt[16], ct[16], tag[16], back[16];
    int rc;

    fill_key_nonce(key, nonce);
    memset(pt, 0x33, sizeof(pt));
    memset(back, 0, sizeof(back));
    rc = qc_aead_encrypt(key, 32, nonce, 12, NULL, 0, pt, sizeof(pt),
                         ct, tag);
    TEST_ASSERT_EQUAL_INT(QC_AEAD_OK, rc);

    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_KEY,
                          qc_aead_decrypt(NULL, 32, nonce, 12, NULL, 0,
                                          ct, sizeof(ct), tag, back));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_LENGTH,
                          qc_aead_decrypt(key, 32, NULL, 12, NULL, 0,
                                          ct, sizeof(ct), tag, back));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_KEY,
                          qc_aead_decrypt(key, 24, nonce, 12, NULL, 0,
                                          ct, sizeof(ct), tag, back));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_LENGTH,
                          qc_aead_decrypt(key, 32, nonce, 11, NULL, 0,
                                          ct, sizeof(ct), tag, back));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_LENGTH,
                          qc_aead_decrypt(key, 32, nonce, 12, NULL, 0,
                                          NULL, sizeof(ct), tag, back));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_LENGTH,
                          qc_aead_decrypt(key, 32, nonce, 12, NULL, 0,
                                          ct, sizeof(ct), tag, NULL));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_LENGTH,
                          qc_aead_decrypt(key, 32, nonce, 12, NULL, 0,
                                          ct, sizeof(ct), NULL, back));
    TEST_ASSERT_EQUAL_INT(QC_AEAD_BAD_LENGTH,
                          qc_aead_decrypt(key, 32, nonce, 12, NULL, 1,
                                          ct, sizeof(ct), tag, back));
    /* Empty input with NULL buffers is legal (length 0 touches nothing).
     * Needs the tag for the empty message, not the tag from above. */
    {
        uint8_t empty_tag[16];
        TEST_ASSERT_EQUAL_INT(QC_AEAD_OK,
                              qc_aead_encrypt(key, 32, nonce, 12, NULL, 0,
                                              NULL, 0, NULL, empty_tag));
        TEST_ASSERT_EQUAL_INT(QC_AEAD_OK,
                              qc_aead_decrypt(key, 32, nonce, 12, NULL, 0,
                                              NULL, 0, empty_tag, back));
    }
}

/* Tamper events -> AUTH_FAIL with output wiped; overlap -> BAD_LENGTH
 * (caller bug, never a tamper event); in-place (pt == ct) is legal. */
static void test_misuse_taxonomy(void) {
    uint8_t key[32], nonce[12], pt[16], ct[16], tag[16], back[16];
    uint8_t badtag[16], buf[17];
    int rc;

    fill_key_nonce(key, nonce);
    for (int i = 0; i < 16; i++) {
        pt[i] = (uint8_t)(0x30 + i);
    }
    rc = qc_aead_encrypt(key, 32, nonce, 12, NULL, 0, pt, sizeof(pt),
                         ct, tag);
    TEST_ASSERT_EQUAL_INT(QC_AEAD_OK, rc);

    /* Tampered tag -> AUTH_FAIL, output wiped. */
    memcpy(badtag, tag, 16);
    badtag[0] ^= 0x01;
    memset(back, 0x5A, sizeof(back));
    rc = qc_aead_decrypt(key, 32, nonce, 12, NULL, 0, ct, sizeof(ct),
                         badtag, back);
    TEST_ASSERT_EQUAL_INT_MESSAGE(QC_AEAD_AUTH_FAIL, rc, "tamper");
    for (size_t i = 0; i < sizeof(back); i++) {
        TEST_ASSERT_EQUAL_UINT8_MESSAGE(0, back[i], "wiped on fail");
    }
    /* Tampered ciphertext -> AUTH_FAIL. */
    ct[0] ^= 0x01;
    TEST_ASSERT_EQUAL_INT(QC_AEAD_AUTH_FAIL,
                          qc_aead_decrypt(key, 32, nonce, 12, NULL, 0,
                                          ct, sizeof(ct), tag, back));
    ct[0] ^= 0x01; /* restore */

    /* In-place encrypt and decrypt (pt == ct) are supported. */
    memcpy(back, pt, sizeof(pt));
    rc = qc_aead_encrypt(key, 32, nonce, 12, NULL, 0,
                         back, sizeof(back), back, tag);
    TEST_ASSERT_EQUAL_INT_MESSAGE(QC_AEAD_OK, rc, "in-place enc");
    TEST_ASSERT_EQUAL_UINT8_ARRAY_MESSAGE(ct, back, 16, "in-place ct");
    memcpy(back, ct, sizeof(ct));
    rc = qc_aead_decrypt(key, 32, nonce, 12, NULL, 0,
                         back, sizeof(back), tag, back);
    TEST_ASSERT_EQUAL_INT_MESSAGE(QC_AEAD_OK, rc, "in-place");
    TEST_ASSERT_EQUAL_UINT8_ARRAY_MESSAGE(pt, back, 16, "in-place pt");

    /* Forward overlap (output starts inside the input region) is a
     * caller bug: BAD_LENGTH, never AUTH_FAIL. Only this direction is
     * rejected by the backend; backward overlap is not contracted, so
     * the test pins only the rejected direction. */
    memcpy(buf, pt, 16);
    rc = qc_aead_encrypt(key, 32, nonce, 12, NULL, 0,
                         buf, 16, buf + 1, tag);
    TEST_ASSERT_EQUAL_INT_MESSAGE(QC_AEAD_BAD_LENGTH, rc, "overlap enc");
    memcpy(buf, ct, 16);
    rc = qc_aead_decrypt(key, 32, nonce, 12, NULL, 0,
                         buf, 16, tag, buf + 1);
    TEST_ASSERT_EQUAL_INT_MESSAGE(QC_AEAD_BAD_LENGTH, rc, "overlap dec");
}

